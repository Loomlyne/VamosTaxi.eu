import { start, open, goPricing, signIn, dlgText, S, db, goLiveInfo, gl } from "./lib.mjs";
await start({ evidenceDir: process.argv[2] });
const s = await open({ viewport: 1440, name: "s1440" });
await signIn(s);
await goPricing(s);
s.page.on("response", r => { if (r.url().includes("/api/staff")) console.log("API", r.request().method(), r.url().replace(/^.*\/api/, "/api"), r.status()); });
const badgeBtn = () => s.page.locator("[data-draft-btn]").first();
await badgeBtn().click(); await s.page.waitForTimeout(700);
await s.page.locator('[role="dialog"] button', { hasText: /^edit class$/i }).click(); await s.page.waitForTimeout(900);
const inc = s.page.locator('[role="dialog"] button[aria-label="Increase"]');
await inc.nth(1).click(); await inc.nth(1).click(); await inc.nth(1).click();
console.log("editor:", await dlgText(s.page));
await s.page.locator('[role="dialog"] button', { hasText: /^save class$/i }).click(); await s.page.waitForTimeout(3000);
console.log("DB:", db("select passenger_capacity, luggage_capacity, active from public.vehicle_classes where name = 'Lab Draft Class'"));
console.log("row after save:", await s.page.evaluate(() => [...document.querySelectorAll("tr")].find(r => r.innerText.includes("Lab Draft Class"))?.innerText.replace(/\s+/g, " ")));
await badgeBtn().click(); await s.page.waitForTimeout(800);
console.log("badge right after save:", gl(await goLiveInfo(s.page)));
await s.page.keyboard.press("Escape"); await s.page.waitForTimeout(6000);
await badgeBtn().click(); await s.page.waitForTimeout(800);
console.log("badge 6s later:", gl(await goLiveInfo(s.page)));
await s.page.keyboard.press("Escape"); await s.page.waitForTimeout(500);
console.log("PRICING PANE TEXT:\n" + (await s.page.evaluate(() => document.body.innerText)).slice(0, 3500));
console.log(db("select id,status,label from public.rate_versions order by id"));
process.exit(0);
