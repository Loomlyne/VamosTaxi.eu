// Run 4: GO LIVE focus return (S3) after fix 774be80a. Lab p30c only.
import { start, open, finish } from "/Users/koss/.vamos-scratch/p30-clean/scripts/test-lab/lab-browser.mjs";
import fs from "node:fs";
const DASH = process.env.LAB_DASH;
const ev = new URL(".", import.meta.url).pathname;
const f = Object.fromEntries(fs.readFileSync(process.env.LAB_ADMIN_FILE, "utf8").split("\n").filter(Boolean).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
await start({ evidenceDir: ev });
const s = await open({ viewport: 1440 });
const { page } = s;
await page.goto(DASH + "/login", { waitUntil: "networkidle" });
const auth = await page.evaluate(async ({ email, password }) => (await fetch("/api/auth", { method: "POST", headers: { "content-type": "application/json" }, credentials: "same-origin", body: JSON.stringify({ locale: "en", mode: "signin", method: "password", email, password }) })).json(), { email: f.email, password: f.password });
console.log("auth", JSON.stringify(auth));
await page.goto(DASH + "/pricing", { waitUntil: "networkidle" });
await page.locator("button[data-set-item]").nth(1).click();
await page.waitForTimeout(800);
const btn = page.locator('button[data-draft-btn]').first();
await btn.waitFor({ timeout: 20000 });
const id = await btn.getAttribute("data-class-id");
await btn.click();
const go = page.locator('[data-golive] button', { hasText: /^go live$/i }).first();
await go.waitFor({ timeout: 10000 });
await page.waitForFunction((b) => !b.disabled, await go.elementHandle(), { timeout: 10000 });
await go.click();
await page.waitForSelector('[data-golive]', { state: "detached", timeout: 15000 }).catch(() => {});
await page.waitForTimeout(2000);
const a = await page.evaluate(() => { const e = document.activeElement; return { tag: e && e.tagName, cls: e && e.getAttribute("data-class-id"), live: !!(e && e.hasAttribute("data-live-badge")) }; });
await page.screenshot({ path: ev + "s1440-S3-focus.png" });
console.log("target", id, "active", JSON.stringify(a));
console.log(a.cls === id ? "PASS | S3-focus | focus on the class row's LIVE badge" : "FAIL | S3-focus | focus not on the row");
await finish();
