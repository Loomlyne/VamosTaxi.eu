import { start, open, goPricing, signIn, dlgText, S, db, goLiveInfo, gl, retireInfo } from "./lib.mjs";
await start({ evidenceDir: process.argv[2] });
const s = await open({ viewport: 1440, name: "s1440" });
await signIn(s);
s.page.on("response", async (r) => { if (r.url().includes("/api/staff") && r.request().method() !== "GET") console.log("API", r.request().method(), r.url().replace(/^.*\/api/, "/api"), r.status(), (await r.text().catch(() => "")).slice(0, 120)); });
await goPricing(s);
const rowOf = (n) => s.page.locator("tr", { has: s.page.locator("[data-class-name]", { hasText: new RegExp(`^${n}$`) }) });
console.log("start versions:", db("select id,status from public.rate_versions order by id").replace(/\n/g, " ; "));
await S("S4", "Retire Lab Draft Class", async () => {
  const cnt0 = await s.page.locator("[data-retired-count]").innerText();
  await rowOf("Lab Draft Class").locator('button[aria-label="Retire"]').click(); await s.page.waitForTimeout(1200);
  const info = await retireInfo(s.page);
  await s.page.locator('[role="dialog"] textarea').fill("No longer offered");
  await s.shot("S4-dialog");
  await s.page.locator('[role="dialog"] button', { hasText: /^retire$/i }).click(); await s.page.waitForTimeout(3000);
  const cnt1 = await s.page.locator("[data-retired-count]").innerText();
  const gone = (await rowOf("Lab Draft Class").count()) === 0;
  const focus = await s.page.evaluate(() => { const a = document.activeElement; return a ? `${a.tagName} ${a.hasAttribute("data-retired-head") ? "data-retired-head" : a.outerHTML.slice(0, 100)}` : "none"; });
  const dbr = db("select hidden_at is not null, hidden_reason from public.vehicle_classes where name = 'Lab Draft Class'");
  const ok = gone && cnt0 === "1" && cnt1 === "2" && /data-retired-head/.test(focus) && dbr === "t|No longer offered";
  return { s, ok, evidence: `dialog title "${info.title}" notes ${JSON.stringify(info.notes)} lastLive=${info.lastLive}; row gone from table: ${gone}; retired count ${cnt0} -> ${cnt1}; focus ${focus}; db ${dbr}` };
}, { s });
await S("S5", "Open Retired classes list", async () => {
  const head = s.page.locator("[data-retired-head]");
  const chevron = async () => head.evaluate((e) => [...e.querySelectorAll("[aria-hidden]")].map((i) => (getComputedStyle(i).maskImage || "").replace(/.*icons\//, "").replace(/["')]/g, "")).join(","));
  const c0 = await chevron(), exp0 = await head.getAttribute("aria-expanded");
  await head.click(); await s.page.waitForTimeout(1000);
  const c1 = await chevron(), exp1 = await head.getAttribute("aria-expanded");
  const rows = await s.page.evaluate(() => [...document.querySelectorAll("[data-retired-row]")].map((r) => ({ t: r.innerText.replace(/\s+/g, " ").trim(), btn: [...r.querySelectorAll("button")].map((b) => b.innerText.trim()).join("/") })));
  await s.shot("S5-retired-open");
  const ok = rows.length === 2 && rows.some((r) => r.t.includes("Lab old class") && r.t.includes("Lab: retired before the run") && /bring back/i.test(r.btn)) && rows.some((r) => r.t.includes("Lab Draft Class") && r.t.includes("No longer offered") && /bring back/i.test(r.btn)) && /up/.test(c1);
  return { s, ok, evidence: `chevron closed ${c0} (expanded ${exp0}) -> open ${c1} (expanded ${exp1}); rows ${JSON.stringify(rows)}` };
}, { s });
let half1 = null;
await S("S14", "Bring back, badge, stand-in publish, badge", async () => {
  const r = s.page.locator("[data-retired-row]", { hasText: "Lab Draft Class" });
  await r.locator("button").filter({ hasText: /bring back/i }).first().click(); await s.page.waitForTimeout(3000);
  const inTable = await rowOf("Lab Draft Class").count();
  const badge = inTable ? await rowOf("Lab Draft Class").locator("[data-draft-btn]").innerText().catch(() => "no draft btn: " + "") : "none";
  const rowTxt = inTable ? (await rowOf("Lab Draft Class").innerText()).replace(/\s+/g, " ") : "";
  const inRetired = await s.page.locator("[data-retired-row]", { hasText: "Lab Draft Class" }).count();
  const cnt = await s.page.locator("[data-retired-count]").innerText();
  await rowOf("Lab Draft Class").locator("[data-draft-btn]").click(); await s.page.waitForTimeout(800);
  const o1 = await goLiveInfo(s.page);
  await s.shot("S14-after-bring-back");
  const dbr = db("select hidden_at is null, active, hidden_reason is null from public.vehicle_classes where name = 'Lab Draft Class'");
  console.log("half1:", `in table ${inTable}; badge ${badge}; row "${rowTxt}"; in Retired list ${inRetired}; count ${cnt}; ${gl(o1)}; db ${dbr}`);
  console.log("versions now:", db("select id,status from public.rate_versions order by id").replace(/\n/g, " ; "), "| class rows per version:", db("select dr.rate_version_id, dr.base_fare_rappen, dr.per_km_rappen from public.distance_rates dr join public.vehicle_classes vc on vc.id=dr.vehicle_class_id where vc.name='Lab Draft Class' order by 1").replace(/\n/g, " ; "));
  // second half
  await s.page.keyboard.press("Escape"); await s.page.waitForTimeout(500);
  await rowOf("Lab Draft Class").locator('button[aria-label="Edit"]').click(); await s.page.waitForTimeout(900);
  const inputs = s.page.locator('[role="dialog"] input:not([type=file])');
  console.log("editor values before:", await inputs.evaluateAll(a => a.map(i => i.value)));
  await inputs.nth(1).fill("0.01"); await inputs.nth(3).fill("0.01"); await s.page.waitForTimeout(300);
  await s.page.locator('[role="dialog"] button', { hasText: /^save class$/i }).click(); await s.page.waitForTimeout(3000);
  await s.page.getByRole("button", { name: /publish fare book/i }).first().click(); await s.page.waitForTimeout(1500);
  const d1 = await dlgText(s.page);
  await s.page.locator('[role="dialog"] button', { hasText: /^publish fare book$/i }).click(); await s.page.waitForTimeout(3500);
  const d2 = await dlgText(s.page);
  await rowOf("Lab Draft Class").locator("[data-draft-btn]").click(); await s.page.waitForTimeout(800);
  const o2 = await goLiveInfo(s.page);
  await s.shot("S14-after-publish");
  const vers = db("select id,status from public.rate_versions order by id").replace(/\n/g, " ; ");
  const first = inTable === 1 && badge === "DRAFT" && inRetired === 0;
  const price1 = o1.items.find(i => i.startsWith("Price in the live price book"));
  const price2 = o2.items.find(i => i.startsWith("Price in the live price book"));
  const ok = first && /=missing/.test(price1) && /=done/.test(price2);
  return { s, ok, evidence: `AFTER BRING BACK: in table ${inTable}, badge ${badge}, in Retired list ${inRetired}, Retired count ${cnt}, ${gl(o1)}, db(not hidden|active|reason null) ${dbr}. AFTER STAND-IN PUBLISH: confirm "${d1}", after "${d2}", versions ${vers}, ${gl(o2)}` };
}, { s });
process.exit(0);
