import { start, open, goPricing, signIn, dlgText, S, db, goLiveInfo, gl, BASE } from "./lib.mjs";
await start({ evidenceDir: process.argv[2] });
const s = await open({ viewport: 1440, name: "s1440" });
await signIn(s);
s.page.on("response", async (r) => { if (r.url().includes("/api/staff") && r.request().method() !== "GET") console.log("API", r.request().method(), r.url().replace(/^.*\/api/, "/api"), r.status(), (await r.text().catch(() => "")).slice(0, 400)); });
await goPricing(s);
await S("S12", "bags 3, publish draft without Lab Draft Class amounts", async () => {
  const badgeBtn = () => s.page.locator("[data-draft-btn]").first();
  await badgeBtn().click(); await s.page.waitForTimeout(700);
  await s.page.locator('[role="dialog"] button', { hasText: /^edit class$/i }).click(); await s.page.waitForTimeout(900);
  const inc = s.page.locator('[role="dialog"] button[aria-label="Increase"]');
  await inc.nth(1).click(); await s.page.waitForTimeout(300);
  console.log("editor:", (await dlgText(s.page)).match(/Max passengers.*?CANCEL/)?.[0]);
  await s.page.locator('[role="dialog"] button', { hasText: /^save class$/i }).click(); await s.page.waitForTimeout(3000);
  const bagsDb = db("select passenger_capacity, luggage_capacity from public.vehicle_classes where name='Lab Draft Class'");
  console.log("bags db:", bagsDb, "| versions:", db("select id,status,label from public.rate_versions order by id").replace(/\n/g, " ; "));
  console.log("draft amounts for Lab Draft Class:", db("select count(*) from public.distance_rates dr join public.vehicle_classes vc on vc.id=dr.vehicle_class_id where vc.name='Lab Draft Class'"));
  await s.page.getByRole("button", { name: /publish fare book/i }).first().click(); await s.page.waitForTimeout(1500);
  const d1 = await dlgText(s.page);
  await s.shot("S12-publish-dialog");
  await s.page.locator('[role="dialog"] button', { hasText: /^publish fare book$/i }).click(); await s.page.waitForTimeout(3500);
  const d2 = await dlgText(s.page);
  const pageErr = await s.page.evaluate(() => (document.body.innerText.match(/[^\n]*(missing|gaps? before)[^\n]*/g) || []).join(" // "));
  await s.shot("S12-after-publish");
  const vers = db("select id,status,label from public.rate_versions order by id").replace(/\n/g, " ; ");
  const slugs = db("select vc.slug from public.distance_rates dr join public.rate_versions rv on rv.id = dr.rate_version_id join public.vehicle_classes vc on vc.id = dr.vehicle_class_id where rv.status = 'live' order by 1").replace(/\n/g, ",");
  const ok = bagsDb === "3|3" && slugs === "business,economy,van" && !/Lab Draft Class/.test(d2 + pageErr);
  return { s, ok, evidence: `bags db ${bagsDb}; confirm dialog "${d1}"; after confirm dialog "${d2}"; page lines "${pageErr}"; versions ${vers}; live book slugs ${slugs}` };
}, { s });
process.exit(0);
